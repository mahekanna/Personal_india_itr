def test_comparison_prefers_the_cheaper_regime():
    tr = make_return(1_500_000)
    tr.deductions.s80c = D(150_000)
    tr.deductions.s80ccd1b = D(50_000)
    tr.deductions.s80d_self = D(25_000)
    comparison = compare_regimes(tr)
    assert comparison.recommended in ("new", "old")
    cheaper = min(comparison.new.total_tax_liability,
                  comparison.old.total_tax_liability)
    assert comparison.chosen.total_tax_liability == cheaper


def test_explicit_regime_choice_overrides_the_recommendation():
    tr = make_return(1_500_000, regime_choice="old")
    assert compare_regimes(tr).recommended == "old"


