# A filing date on or before the due date, so interest never muddies a slab test.
ON_TIME = date(2026, 7, 25)


def make_return(salary: int = 0, **kwargs) -> TaxReturn:
    tr = TaxReturn(assessment_year="2026-27", filing_date=ON_TIME, **kwargs)
    if salary:
        tr.salaries = [
            SalaryIncome(employer_name="Employer", employer_tan="ABCD12345E",
                         salary_17_1=D(salary))
        ]
    return tr


