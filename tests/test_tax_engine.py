def test_112a_exemption_is_a_rate_threshold_not_a_deduction():
    """The ₹1.25 lakh does not leave total income — section 112A(2)."""
    tr = make_return(1_000_000)
    tr.capital_gains = [
        CapitalGainItem(category="ltcg_112a", description="INFY",
                        sale_consideration=D(825_000),
                        cost_of_acquisition=D(500_000))
    ]
    comp = compute(tr, "new")
    # Total income carries the whole 3,25,000 gain.
    assert comp.gross_total_income == D(1_250_000)
    slice_ = next(s for s in comp.special_slices if s.code == "ltcg_112a")
    assert slice_.income == D(325_000)
    assert slice_.statutory_exemption == D(125_000)
    assert slice_.chargeable == D(200_000)
    assert slice_.tax == D(25_000)          # 12.5% of 2,00,000


