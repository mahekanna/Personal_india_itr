def test_surcharge_on_capital_gains_capped_at_15_percent():
    tr = make_return(3_000_000)
    tr.capital_gains = [
        CapitalGainItem(category="ltcg_112a", sale_consideration=D(30_000_000),
                        cost_of_acquisition=D(0))
    ]
    comp = compute(tr, "old")
    # Total income is above ₹2 crore, so normal income attracts 25% but the
    # capital-gains slice is held to 15%.
    cg_tax = comp.tax_on_special_income
    normal_tax = comp.tax_after_rebate - cg_tax
    expected = normal_tax * D("0.25") + cg_tax * D("0.15")
    assert comp.surcharge == pytest.approx(float(expected), rel=1e-9)


