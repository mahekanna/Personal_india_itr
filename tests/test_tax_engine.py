@pytest.mark.parametrize(
    "gross, expected_total_income, expected_tax_before_rebate",
    [
        # 4L nil band starts after the 75k standard deduction.
        (475_000, 400_000, 0),
        # 8L: 5% on the 4L-8L band = 20,000.
        (875_000, 800_000, 20_000),
        # 12L: 20,000 + 10% of 4L = 60,000. Fully wiped by the rebate.
        (1_275_000, 1_200_000, 60_000),
        # 16L: + 15% of 4L = 1,20,000.
        (1_675_000, 1_600_000, 120_000),
        # 20L: + 20% of 4L = 2,00,000.
        (2_075_000, 2_000_000, 200_000),
        # 24L: + 25% of 4L = 3,00,000.
        (2_475_000, 2_400_000, 300_000),
        # 30L: 3,00,000 + 30% of 6L = 4,80,000.
        (3_075_000, 3_000_000, 480_000),
    ],
)
def test_new_regime_slab_boundaries(gross, expected_total_income,
                                    expected_tax_before_rebate):
    comp = compute(make_return(gross), "new")
    assert comp.total_income == D(expected_total_income)
    assert comp.tax_on_normal_income == D(expected_tax_before_rebate)


def test_standard_deduction_is_75000_in_new_regime():
    comp = compute(make_return(1_000_000), "new")
    assert comp.salary == D(925_000)


def test_standard_deduction_is_50000_in_old_regime():
    comp = compute(make_return(1_000_000), "old")
    assert comp.salary == D(950_000)


