def test_87a_makes_1275000_salary_tax_free():
    """The headline promise of the Finance Act 2025."""
    comp = compute(make_return(1_275_000), "new")
    assert comp.total_income == D(1_200_000)
    assert comp.rebate_87a == D(60_000)
    assert comp.total_tax_liability == D(0)


def test_87a_marginal_relief_just_above_the_ceiling():
    """At ₹12,10,000 of total income the tax may not exceed the ₹10,000 excess."""
    tr = make_return(1_285_000)          # 12,85,000 - 75,000 = 12,10,000
    comp = compute(tr, "new")
    assert comp.total_income == D(1_210_000)
    # Slab tax would be 61,500; relief caps the payable at the 10,000 excess.
    assert comp.tax_on_normal_income == D(61_500)
    assert comp.tax_after_rebate == D(10_000)


def test_87a_denied_against_capital_gains_in_new_regime():
    """Section 115BAC(1A) allows the rebate only against slab-rate income."""
    tr = make_return(400_000)
    tr.capital_gains = [
        CapitalGainItem(category="stcg_111a", description="Equity",
                        sale_consideration=D(500_000),
                        cost_of_acquisition=D(200_000))
    ]
    comp = compute(tr, "new")
    # Normal income is 3,25,000 — below the 4L exemption, so no slab tax. The
    # unused 75,000 shelters part of the gain; the rest is taxed at 20% with no
    # rebate available against it.
    assert comp.tax_on_normal_income == D(0)
    assert comp.rebate_87a == D(0)
    assert comp.tax_on_special_income > 0


def test_old_regime_87a_ceiling_is_500000():
    comp = compute(make_return(550_000), "old")
    assert comp.total_income == D(500_000)
    assert comp.rebate_87a == D(12_500)
    assert comp.total_tax_liability == D(0)


